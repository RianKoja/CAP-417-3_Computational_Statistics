import numpy as np
import pandas as pd
from scipy import stats
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from pathlib import Path

SCRIPT_DIR = Path(__file__).parent
N_VALUES = [100, 1000, 10000]
RNG = np.random.default_rng(seed=42)

HISTOGRAM_DISCUSSIONS = {
    100: (
        "# Histogram Analysis — N=100\n\n"
        "With only 100 points the histogram is coarse and irregular. "
        "The Brownian motion (cumulative sum of Gaussian increments) produces a distribution "
        "that spreads far from zero as the walk drifts, so the histogram tends to look flat or "
        "multi-modal rather than a clean bell-curve. "
        "The small sample size means each bin may contain just a few observations, "
        "making it hard to identify any underlying shape reliably. "
        "Visually the distribution appears roughly symmetric but with heavy tails — "
        "consistent with the non-stationary nature of Brownian motion.\n"
    ),
    1000: (
        "# Histogram Analysis — N=1000\n\n"
        "With 1 000 points a clearer picture emerges. "
        "The Brownian walk accumulates displacement over time, so the marginal distribution "
        "of its values is approximately Gaussian (by the Central Limit Theorem applied to the "
        "partial sums). The histogram shows a roughly bell-shaped, unimodal distribution, "
        "but with notable spread compared to the underlying Gaussian increments. "
        "The symmetry is better than at N=100, and tails are more visible. "
        "Slight asymmetry (skewness) may still appear due to random drift.\n"
    ),
    10000: (
        "# Histogram Analysis — N=10000\n\n"
        "At 10 000 points the histogram converges to a smooth, approximately Gaussian shape. "
        "The law of large numbers smooths out sampling noise, revealing the underlying "
        "distribution of Brownian motion positions clearly. "
        "The distribution is unimodal and roughly symmetric around its mean (which drifts "
        "from zero). The tails remain heavier than a standard normal because the walk can "
        "wander arbitrarily far. Kurtosis values close to 3 (Pearson) confirm near-Gaussian "
        "behaviour, and skewness approaches zero as expected for a symmetric random walk.\n"
    ),
}


def generate_brownian_series(n: int) -> np.ndarray:
    """Generate Brownian motion as cumulative sum of Gaussian noise."""
    noise = RNG.standard_normal(n)
    return np.cumsum(noise)


for N in N_VALUES:
    series = generate_brownian_series(N)

    # --- Part 1: Save time series ---
    df_series = pd.DataFrame({"time_step": np.arange(N), "value": series})
    df_series.to_parquet(SCRIPT_DIR / f"tseries_{N}.parquet", index=False)
    print(f"[N={N}] Time series saved.")

    # --- Part 2: Histogram ---
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.hist(series, bins="auto", color="#2E86AB", edgecolor="white", density=True)

    # Overlay fitted normal for reference
    x = np.linspace(series.min(), series.max(), 300)
    mu, sigma = series.mean(), series.std(ddof=1)
    ax.plot(x, stats.norm.pdf(x, mu, sigma), color="#E84855", linewidth=1.8,
            label=f"Normal fit\nμ={mu:.2f}, σ={sigma:.2f}")
    ax.legend(fontsize=9)
    ax.set_title(f"Histogram of Brownian Motion (N={N})", fontsize=13)
    ax.set_xlabel("Value")
    ax.set_ylabel("Density")
    fig.tight_layout()
    fig.savefig(SCRIPT_DIR / f"histogram_{N}.svg", format="svg")
    plt.close(fig)
    print(f"[N={N}] Histogram saved.")

    # --- Part 2 (cont): qualitative discussion ---
    md_path = SCRIPT_DIR / f"histogram_{N}.md"
    md_path.write_text(HISTOGRAM_DISCUSSIONS[N], encoding="utf-8")
    print(f"[N={N}] Markdown discussion saved.")

    # --- Part 3: Statistical moments ---
    mean_val = float(np.mean(series))
    variance_val = float(np.var(series, ddof=1))
    skewness_val = float(stats.skew(series))
    # Fisher definition: excess kurtosis (normal → 0)
    kurtosis_fisher = float(stats.kurtosis(series, fisher=True))
    # Pearson definition: non-excess (normal → 3)
    kurtosis_pearson = float(stats.kurtosis(series, fisher=False))

    df_moments = pd.DataFrame({
        "N": [N],
        "mean": [mean_val],
        "variance": [variance_val],
        "skewness": [skewness_val],
        "kurtosis_fisher": [kurtosis_fisher],
        "kurtosis_pearson": [kurtosis_pearson],
    })
    df_moments.to_parquet(SCRIPT_DIR / f"moments_{N}.parquet", index=False)
    print(
        f"[N={N}] Moments: mean={mean_val:.4f}, var={variance_val:.4f}, "
        f"skew={skewness_val:.4f}, kurt_Fisher={kurtosis_fisher:.4f}, "
        f"kurt_Pearson={kurtosis_pearson:.4f}"
    )
    print()

print("All outputs generated successfully.")
